const messages: Record<string, Record<Key, string>> = { fr, en };

export type MessageKey = Key;

export const i18n = reactive({ lang: 'fr' });

/** fr_FR, fr-FR, FR → fr; languages without translation → en. */
export function setLang(lang: string) {
  const code = String(lang || '').slice(0, 2).toLowerCase();
  i18n.lang = code in messages ? code : 'en';
  document.documentElement.lang = i18n.lang;
}

export function t(key: Key, params: Record<string, string | number> = {}) {
  const text = messages[i18n.lang]?.[key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

/** Validation errors of lib/coverage.js (`{ code, value }`) in the current language. */
export function errorText(error: { code: string; value?: string }) {
  return t(`error.${error.code}` as Key, { value: error.value ?? '' });
}
